#!/bin/bash
# Module 10 must not move a failed or stopped AIDE init into place, or report
# success for one. A stopped init leaves an empty database behind.
source "${REPO_ROOT:-/repo}/tests/lib/assert.sh"
require_root
require_cmd gzip

REPO="${REPO_ROOT:-/repo}"
export LOG_FILE="${TMPDIR:-/tmp}/uh_aide_baseline_$$.log"
_lib='source "'"$REPO"'/lib/core.sh"
      source "'"$REPO"'/lib/platform.sh"
      source "'"$REPO"'/lib/modules.sh"'
AIDE_DIR=/var/lib/aide
GOOD=$'@@begin_db\n/etc/passwd 0\n@@end_db\n'
stub_dir=$(mktemp -d)
mkdir -p "$AIDE_DIR"

# The stub stands in for aide --init: it runs the given shell, then exits with the status.
run_module() {   # <init shell> <exit status>
    printf '#!/bin/sh\n%s\nexit %s\n' "$1" "$2" > "$stub_dir/aide"
    chmod +x "$stub_dir/aide"
    bash -c "set -euo pipefail; $_lib
        PATH='$stub_dir':\$PATH
        command() { [[ \"\${2:-}\" == aideinit ]] && return 1; builtin command \"\$@\"; }
        DISTRO_TYPE=debian; DRY_RUN=false
        count_fix() { echo FIX-COUNTED; }
        apply_aide; echo REACHED-END" 2>&1 || true
}
reset() { rm -f "$AIDE_DIR"/aide.db "$AIDE_DIR"/aide.db.gz "$AIDE_DIR"/aide.db.new "$AIDE_DIR"/aide.db.new.gz /etc/cron.daily/aide-check; }
assert_no_success() {   # <output> <label>
    if grep -qE 'AIDE baseline created|FIX-COUNTED' <<< "$1"; then
        fail "$2: reported success"
    else
        pass_msg "$2: no success reported"
    fi
    assert_output_contains "$1" 'REACHED-END' "$2: does not abort the caller"
}

# --- a stopped init leaves an empty file, which must not be moved into place ---
reset
out=$(run_module ': > /var/lib/aide/aide.db.new.gz' 0)
assert_no_success "$out" "empty .new.gz"
assert_output_contains "$out" 'empty or corrupt' "empty .new.gz: warned"
assert_file_absent "$AIDE_DIR/aide.db.gz" "empty .new.gz: not moved into place"

# --- an empty database in place is rebuilt, with a copy kept ------------------
reset; : > "$AIDE_DIR/aide.db"
out=$(run_module 'printf "@@begin_db\n@@end_db\n" > /var/lib/aide/aide.db.new' 0)
assert_output_contains "$out" 'AIDE baseline created' "empty live database: rebuilt"
[[ -s "$AIDE_DIR/aide.db" ]] && pass_msg "empty live database: replaced" || fail "empty live database: still empty"
rm -f "$AIDE_DIR"/aide.db.bak-*

# --- AIDE 0.16's plain database has no end marker, and must not be rebuilt ----
reset; printf '@@begin_db\n# This file was generated by Aide, version 0.16\n/etc/passwd 0\n' > "$AIDE_DIR/aide.db"
out=$(run_module 'echo INIT-RAN > /tmp/uh_init_ran' 0)
assert_output_contains "$out" 'already present, kept' "AIDE 0.16 database: kept"
# --- a newer database cut off before its end marker is still corrupt ----------
reset; printf '@@begin_db\n# This file was generated by Aide, version 0.18.6\n/etc/passwd 0\n' > "$AIDE_DIR/aide.db"
out=$(run_module ':' 0)
assert_output_contains "$out" 'no usable database' "truncated newer database: not kept"
rm -f "$AIDE_DIR"/aide.db.bak-*

# --- init failed: a leftover .new from an earlier run must not be promoted ---
reset; printf '%s' "$GOOD" > "$AIDE_DIR/aide.db.new"
out=$(run_module ':' 14)
assert_no_success "$out" "failed init"
assert_output_contains "$out" 'exit 14' "failed init: exit status named"
assert_file_absent "$AIDE_DIR/aide.db"

# --- truncated gzip, and init that writes nothing -----------------------------
reset; out=$(run_module 'printf "@@begin_db\n" | gzip -c | head -c 12 > /var/lib/aide/aide.db.new.gz' 0)
assert_no_success "$out" "truncated .new.gz"
assert_file_absent "$AIDE_DIR/aide.db.gz"
reset; out=$(run_module ':' 0)
assert_no_success "$out" "no database written"
assert_output_contains "$out" 'no usable database' "no database written: warned"

# --- valid databases, plain and gzipped, are promoted -------------------------
reset; out=$(run_module 'printf "@@begin_db\n@@end_db\n" > /var/lib/aide/aide.db.new' 0)
assert_output_contains "$out" 'AIDE baseline created' "plain: success reported"
assert_output_contains "$out" 'FIX-COUNTED' "plain: fix counted"
assert_file_exists "$AIDE_DIR/aide.db"
reset; out=$(run_module 'printf "@@begin_db\n@@end_db\n" | gzip -c > /var/lib/aide/aide.db.new.gz' 0)
assert_output_contains "$out" 'AIDE baseline created' "gzip: success reported"
assert_file_exists "$AIDE_DIR/aide.db.gz"
assert_file_absent "$AIDE_DIR/aide.db.new.gz"

reset; rm -rf "$stub_dir"
finish
